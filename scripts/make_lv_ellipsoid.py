# make_lv_ellipsoid.py
# Build an LV ellipsoid case from an anatomy file: mesh, DG0 fibres, activation map,
# cell types, ECG electrodes, and the case.toml that run_em.py reads.
# Usage: python3 scripts/make_lv_ellipsoid.py cases/lv_ellipsoid/anatomy.toml
# Writes next to the anatomy file: geometry/, case.toml, geometry_report.json.
# For a variant, copy the case folder, edit anatomy.toml, rerun.
import argparse
import json
import shutil
import tomllib
from dataclasses import asdict
from pathlib import Path

import numpy as np
from mpi4py import MPI

from physcardems import ellipsoid as ell

assert MPI.COMM_WORLD.size == 1, "run this serially"
ap = argparse.ArgumentParser()
ap.add_argument("anatomy")
args = ap.parse_args()

path = Path(args.anatomy).resolve()
with open(path, "rb") as f:
    spec = tomllib.load(f)
casedir = path.parent
name = spec.get("name", casedir.name)
anatomy = ell.Anatomy(**spec.get("anatomy", {}))
activation = ell.Activation(**spec.get("activation", {}))
celltypes = ell.CellTypes(**spec.get("celltypes", {}))

geodir = casedir / "geometry"
if geodir.exists():
    shutil.rmtree(geodir)
geo, tmpdir = ell.generate_geometry(geodir, anatomy)
markers = ell.standardise_markers(geo.markers)
fields, roots = ell.ep_node_fields(geo, markers, activation, celltypes)
report = ell.geometry_report(geo, markers)
report["analytic"] = ell.analytic_volumes_ml(anatomy)
report["helix_angle_deg_right_handed_positive"] = ell.helix_angles(geo, fields["transmural"])

lv_centre = np.array([-0.5 * report["cavity_long_axis_mm"] * 1e-3, 0.0, 0.0])
info = {"source": "physcardems.ellipsoid.generate_geometry", "units": "m", "fibre_space": "DG_0",
        "anatomy": asdict(anatomy), "activation": asdict(activation), "celltypes": asdict(celltypes),
        "ep_node_fields": "lat_ms, celltype (0 endo 1 epi 2 mid), sf_IKs, transmural"}
ell.write_case(geodir, geo, markers, fields, ell.electrode_positions(lv_centre), info)
shutil.rmtree(tmpdir, ignore_errors=True)

lat, ct = fields["lat_ms"].x.array, fields["celltype"].x.array
report["lat_total_activation_ms"] = float(lat.max())
report["celltype_fraction_nodes"] = {k: float(np.mean(ct == v)) for k, v in ell.CELLTYPE.items()}
report["activation_roots_m"] = roots.tolist()
(casedir / "geometry_report.json").write_text(json.dumps(report, indent=2))

(casedir / "case.toml").write_text(f'''# {name}: generated by scripts/make_lv_ellipsoid.py from anatomy.toml (edit that, not this)
name = "{name}"

[geometry]
dir = "geometry"
myocardium_cell_tags = [1]
cavities = ["LV"]
base_normal_axis = 0                # basal plane x = 0, held in x so the cavity volume is exact

[geometry.tags]
LV = {markers["LV"][0]}
EPI = {markers["EPI"][0]}
BASE = {markers["BASE"][0]}

[ecg]
electrodes = "geometry/electrodes_m.csv"
unit_scale = 1.0
''')
print(json.dumps({k: v for k, v in report.items() if k != "activation_roots_m"}, indent=2))